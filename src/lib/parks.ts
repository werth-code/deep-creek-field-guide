/**
 * Parks — state and regional.
 *
 * Same convention as everything else here: `null` means UNVERIFIED, never
 * "no". A park with `camping: null` has not been checked; it does not lack a
 * campground. Rendering those as "No" would invent facts ten at a time.
 */

export interface Reservation {
  /** null = we haven't established whether one is needed. */
  required: boolean | null;
  /**
   * WHEN the requirement bites, which is not the same question as whether
   * one exists.
   *
   * Swallow Falls needs a reservation at weekends and on holidays, and lets
   * you walk in on a Tuesday. The badge said "RESERVATION REQUIRED" flatly
   * and the page opened "You can't just turn up" — true of two days in seven,
   * and read as true of all of them. Someone reads that on a Wednesday
   * morning and drives somewhere else for no reason.
   *
   * `null` means the scope isn't established, and the wording stays general.
   */
  scope?: "always" | "weekends" | null;
  window: string | null;
  days: string | null;
  bookAhead: string | null;
  note: string | null;
  /** Entry windows, where the park sells timed slots rather than open entry. */
  slots?: string[] | null;
}

/**
 * A published correction.
 *
 * /how-we-verify/ promises that when we get something wrong we fix it, re-date
 * it, and say on the page that we did. A promise like that is worth nothing
 * without somewhere for it to live, so corrections are part of the record and
 * render on the page rather than being edited away in a commit nobody reads.
 */
export interface Correction {
  /** ISO date the fix was made. */
  date: string;
  /** What we had said. Stated plainly, not softened. */
  was: string;
  /** What it actually is, and how we established that. */
  now: string;
}

/**
 * A field report — someone who was actually there.
 *
 * /how-we-verify/ says a report becomes a dated fact if we can use it. That
 * promise needs somewhere to live, or reports quietly turn into unattributed
 * prose and the site loses the thing it sells.
 *
 * A first-hand visit legitimately counts as `confirmed` under the method
 * ("we called, visited, or asked"). But it confirms a FIELD, not a record:
 * standing in the parking lot tells you where the restrooms are, and nothing
 * about the fee schedule. So reports attach here, name what they bear on, and
 * the record's own tier is unaffected until the rest is checked.
 *
 * `visitedOn` is separate from `receivedOn` on purpose. A report from someone
 * who was there last August is worth less than one from Tuesday, and a site
 * that stamps dates on everything cannot be vague about which date it means.
 */
export interface FieldReport {
  /** ISO date we received it. */
  receivedOn: string;
  /** ISO date they were there. null when they didn't say — and it shows. */
  visitedOn: string | null;
  /** Who. A name, "a reader", or the maintainer. */
  from: string;
  what: string;
  /** Which fields this bears on, for display beside them. */
  affects?: string[];
}

/** A photograph attached to a record. Shape mirrors Photo.astro's props. */
export interface Photo {
  file: string;
  alt: string;
  caption?: string | null;
  credit: string;
  /**
   * When it was taken: `YYYY-MM-DD`, `YYYY-MM`, or null when it isn't known.
   * Renders as "4 Aug 2026", "July 2026" or "date not given" respectively.
   */
  takenOn: string | null;
  portrait?: boolean;
  /**
   * Where to anchor the crop on a listing thumbnail, as a CSS object-position.
   * Defaults to centre.
   *
   * Thumbnails are a fixed 16:9 box and most of these photos are 4:3, so a
   * centre crop throws away the top and bottom eighth. That is usually sky and
   * gravel, and occasionally it is the animal — the first card built here
   * cropped a tortoise's shell off and left a fence. Only set this when the
   * default actually loses the subject.
   */
  focus?: string;
}

/**
 * A field note.
 *
 * Not a fact and not a correction. It is the stuff a database can't hold: the
 * fountain that doesn't work, the walk from the car being longer than the map
 * suggests, the bugs at six in the evening. Dated, signed, first person.
 *
 * WHY IT IS DELIBERATELY NOT A VERIFIED FACT
 *
 * A verified fact is checked with whoever sets the rule and holds until they
 * change it. A field note is one person on one day, and next week the fountain
 * might be fixed. Rendering them the same way would let an impression harden
 * into a claim, which is the failure this whole site is built against. So they
 * get their own block, their own styling, and a byline — and the facts table
 * stays untouched by them.
 *
 * They are also the only thing here that cannot be generated by someone who
 * never went.
 */
export interface FieldNote {
  /** ISO date I was there. Not the date I typed it up. */
  date: string;
  /** Who. Free text so a reader's note can be credited by name. */
  author: string;
  body: string;
  /** Optional photo, keyed like Photo.file. */
  photo?: string | null;
}

/**
 * The verdict.
 *
 * One or two sentences a database could not produce. A fact, then what I
 * actually think about that fact.
 *
 * This is the thing the site was missing. It has the most rigorous data of any
 * guide to this county and, until now, said nothing about anything. The
 * facilities table tells you a park has restrooms. The verdict tells you the
 * walk from the car is longer than it looks and the bugs are bad at six.
 *
 * Rules: no adjective stacks, no closing epigram, and it has to contain
 * something only somebody who went could know. If it reads like it could have
 * been written from the DNR page, delete it and write it again.
 */
export interface Verdict {
  /** One or two sentences. Fact, then reaction. */
  text: string;
  /** ISO date. A verdict ages like everything else here. */
  on: string;
}

export interface StateParkFeatures {
  waterfall: boolean | null;
  /** Sand you can sit on. Distinct from `swimming`, which is about the water. */
  beach: boolean | null;
  swimming: boolean | null;
  /**
   * Added after a reader pointed out Deep Creek Lake has them and the schema
   * had nowhere to say so. State parks had no restroom field at all, which
   * meant the one question people ask most could only be answered for town
   * parks.
   */
  restrooms: boolean | null;
  /**
   * Somewhere to sit and eat. Added when a report named picnic areas at a
   * state park and there was nowhere to record it — town parks had the field
   * and state parks didn't. Third schema gap a field report has found, after
   * restrooms and boat rentals, and all three the same shape: the dataset was
   * built from what agencies publish rather than from what people ask.
   */
  picnic: boolean | null;
  /**
   * Hot showers. Fourth schema gap a field report has found, and the same
   * shape as the other three.
   *
   * This one matters more than it looks. A shower is usually a campground
   * building, and campground buildings are usually for campers only — so
   * "showers: true" and "you can rinse the lake off before the drive home"
   * are not the same claim. The boolean only says they exist; who may use
   * them goes in `warnings`, the same place Herrington Manor's dogs-but-not-
   * on-the-sand rule lives. State parks have no `access` field — town parks
   * grew one for the 4-H centre and this dataset never did.
   */
  showers: boolean | null;
  camping: boolean | null;
  cabins: boolean | null;
  trails: boolean | null;
  boatLaunch: boolean | null;
  /** Renting a boat AT the park — not a private marina elsewhere on the lake. */
  boatRentals: boolean | null;
  fishing: boolean | null;
  winterUse: boolean | null;
  petsAllowed: boolean | null;
}

