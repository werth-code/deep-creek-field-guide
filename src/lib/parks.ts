/**
 * The three that decide whether an outing works, and the reason this site
 * leads with restrooms everywhere. Marked in the data rather than at each
 * render site, so a chip can't be emphasised on one page and not another.
 */
const EMPHASIS = new Set(["restrooms", "water", "showers"]);

export interface Tag {
  key: string;
  label: string;
  emphasis: boolean;
}

const tag = ([key, label]: [string, string]): Tag => ({
  key,
  label,
  emphasis: EMPHASIS.has(key),
});

export const presentState = (p: StatePark): Tag[] =>
  STATE_FEATURE_LABELS.filter(([k]) => p.features[k] === true).map((e) => tag(e as [string, string]));

export const presentRegional = (p: RegionalPark): Tag[] =>
  REGIONAL_FACILITY_LABELS.filter(([k]) => p.facilities[k] === true).map((e) => tag(e as [string, string]));

export function completenessState(p: StatePark) {
  const v = STATE_FEATURE_LABELS.map(([k]) => p.features[k]);
  return { known: v.filter((x) => x !== null && x !== undefined).length, total: v.length };
}

/** Restrooms count as a field here — it's the one people ask about. */
export function completenessRegional(p: RegionalPark) {
  const v: (boolean | null)[] = [
    p.restrooms.present,
    ...REGIONAL_FACILITY_LABELS.map(([k]) => p.facilities[k]),
  ];
  return { known: v.filter((x) => x !== null && x !== undefined).length, total: v.length };
}

/** Reservation status, as a flag with a redundant texture channel. */
/**
 * The reservation rule as one sentence, built from the data.
 *
 * A helper rather than page markup because the index card and the park page
 * both need to say this and must not be able to drift apart. The weekday
 * clause is the whole point: it is the half of the rule that stops someone
 * cancelling a Tuesday.
 */
export function reservationLine(r: Reservation): string | null {
  if (r.required !== true) return null;
  const bits: string[] = [];
  bits.push(
    r.scope === "weekends"
      ? "Weekends and holidays need a day-use reservation. Weekdays you can turn up and pay at the gate"
      : "A day-use reservation is needed",
  );
  if (r.window) bits.push(r.window);
  if (r.bookAhead) bits.push(r.bookAhead.replace(/^Opens /, "Booking opens "));
  return bits.join(". ").replace(/\.\.$/, ".") + ".";
}

export function reservationFlag(r: Reservation): {
  word: string;
  bar: "bar-solid" | "bar-dotted" | "bar-hatch";
  chip: string;
  icon: "check" | "alert" | "cross";
} {
  if (r.required === true)
    return {
      word: r.scope === "weekends" ? "Reservation at weekends" : "Reservation required",
      bar: "bar-hatch",
      chip: "bg-flag-red-bearing text-white",
      icon: "alert",
    };
  if (r.required === false)
    return {
      word: "No reservation needed",
      bar: "bar-solid",
      chip: "bg-flag-green-bearing text-white",
      icon: "check",
    };
  return {
    word: "Not confirmed",
    bar: "bar-dotted",
    chip: "bg-flag-amber text-ink",
    icon: "alert",
  };
}

